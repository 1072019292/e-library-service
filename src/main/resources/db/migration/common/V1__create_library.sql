CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    author VARCHAR(200) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    total_licenses INTEGER NOT NULL CHECK (total_licenses > 0)
);

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    book_id BIGINT NOT NULL REFERENCES books(id),
    borrowed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    returned_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_loan_time CHECK (returned_at IS NULL OR returned_at >= borrowed_at)
);

CREATE INDEX ix_loan_book_active ON loans(book_id, returned_at);
CREATE INDEX ix_loan_user_active ON loans(user_id, returned_at, borrowed_at, id);
